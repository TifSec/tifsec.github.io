-- Base locale fictive : structure des tables pertinentes d’après l’export fourni.
create role anon nologin;
create role authenticated nologin;
create schema auth;
create table auth.users (id uuid primary key);
create function auth.uid() returns uuid language sql stable as
    $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
grant usage on schema auth, public to anon, authenticated;
grant execute on function auth.uid() to anon, authenticated;

create table public.profiles (
    user_id uuid primary key references auth.users(id) on delete cascade,
    prenom text not null, nom text not null, classe text,
    created_at timestamptz not null default now(),
    role text not null default 'student' check (role in ('student', 'teacher')),
    etablissement text
);
alter table public.profiles enable row level security;
grant select on public.profiles to authenticated;
create policy own_profile on public.profiles for select to authenticated using (auth.uid() = user_id);

create table public.work_sessions (
    id bigint generated by default as identity primary key,
    etablissement text not null check (etablissement in ('college', 'mfr')),
    matiere text not null, classe text not null, seance text not null,
    created_by uuid not null references auth.users(id),
    max_members smallint not null default 1 check (max_members between 1 and 3),
    terminee boolean not null default false,
    created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table public.work_session_members (
    id bigint generated by default as identity primary key,
    work_session_id bigint not null references public.work_sessions(id) on delete cascade,
    user_id uuid not null references auth.users(id) on delete cascade,
    status text not null default 'pending' check (status in ('pending', 'accepted', 'declined')),
    joined_at timestamptz, created_at timestamptz not null default now(),
    unique (work_session_id, user_id)
);
create table public.work_answers (
    id bigint generated by default as identity primary key,
    work_session_id bigint not null references public.work_sessions(id) on delete cascade,
    question_key text not null check (length(trim(question_key)) > 0),
    reponse text not null default '', updated_by uuid references auth.users(id),
    created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
    unique (work_session_id, question_key)
);
alter table public.work_sessions enable row level security;
alter table public.work_session_members enable row level security;
alter table public.work_answers enable row level security;
grant all on public.work_sessions, public.work_answers, public.work_session_members to anon, authenticated;
grant update (updated_by) on public.work_answers to authenticated;

